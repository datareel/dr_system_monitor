# shellcheck source=lib/drsm_plugin.sh
source "${DRSM_LIB:-$(dirname "$0")/../../../lib}/drsm_plugin.sh"

target=$(drsm_target) || exit 3
URL=$(drsm_setting URL "")
if [ "${URL}" == "" ]; then URL="ftp://${target}"; fi

drsm_web_probe "${URL}" "FTP" "FTP service"

drsm_exit
